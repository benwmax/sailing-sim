#!/usr/bin/env python3
"""The frigate's gun table for the game (docs/cannon-fire/): reads a build's guns.json (build_frigate.py's game data) and
writes Source/SailingPhysics/Private/FrigateGunData.inl, the FCannonMount rows Sailing::FrigateCannonMounts() returns.

    python3 -I Tools/shipkit/frigate/cannon_data.py <build dir or guns.json> [--out <inl>]

Edit this script or rebuild the model, never the .inl. Every gun: its port's frame in the ship's frame (metres: X forward,
Y to starboard, Z up, as guns.json), its carriage's (or bed's) place along the port's X in each pose, the housed elevation,
the lid's opening and the elevations the port allows. Carronades are never housed: their housed place is run out (they
lie lashed on their slides), their run-in place the recoil's end.
"""
import argparse
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
DEFAULT_OUT = os.path.join(REPO, "Source", "SailingPhysics", "Private", "FrigateGunData.inl")


def f(v):
    return f"{float(v):.6f}"


def vec(v):
    return f"Vec3({f(v[0])}, {f(v[1])}, {f(v[2])})"


def rows(guns):
    out = []
    long24 = guns["long24"]
    housed_elev = long24["elevation"]["poses_deg"]["housed"]
    for g in long24["guns"]:
        fr = g["frame"]
        cx = g["carriage_x_m"]
        lo, hi = g.get("run_out_elevation_deg", [long24["elevation"]["quoin_home_deg"], long24["elevation"]["breech_on_bed_deg"]])
        out.append(dict(kind="Long24", side="Port" if g["side"] == "port" else "Starboard", port=g["port"], id=g["id"],
                        origin=fr["origin_m"], x=fr["x"], y=fr["y"], z=fr["z"], housed=cx["housed"], run_in=cx["run_in"],
                        run_out=cx["run_out"], slide=0.0, elev=housed_elev, lid=g.get("lid_open_deg", 0.0), lo=lo, hi=hi,
                        hinge=g.get("lid_frame")))
    carr = guns["carronade32"]
    for g in carr["guns"]:
        fr = g["frame"]
        bolt = g["fighting_bolt_x_m"]
        out.append(dict(kind="Carronade32", side="Port" if g["side"] == "port" else "Starboard", port=g["port"], id=g["id"],
                        origin=fr["origin_m"], x=fr["x"], y=fr["y"], z=fr["z"], housed=bolt + carr["bed_x_m"]["run_out"],
                        run_in=bolt + carr["bed_x_m"]["recoil"], run_out=bolt + carr["bed_x_m"]["run_out"], slide=bolt,
                        elev=0.0, lid=0.0, lo=-5.0, hi=10.0))
    return out


def write(rs, out_path, source):
    lines = [
        "// Generated by Tools/shipkit/frigate/cannon_data.py from " + source + ": do not edit. The frigate Commonwealth's guns",
        "// (docs/cannon-fire/): kind, side, port, id, the port's frame (origin and X, Y, Z in the ship's frame, m), the carriage's",
        "// place along X housed / run in / run out, a carronade's slide, the housed elevation, the lid's opening, the elevations;",
        "// Hinge(): the row's lid hinge frame, when guns.json gives it (lid_frame).",
        f"// {sum(r['kind'] == 'Long24' for r in rs)} long 24-pounders, {sum(r['kind'] == 'Carronade32' for r in rs)} 32-pounder carronades.",
    ]
    for r in rs:
        lines.append(
            f"Row(ECannonKind::{r['kind']}, ECannonSide::{r['side']}, {int(r['port'])}, \"{r['id']}\", {vec(r['origin'])}, "
            f"{vec(r['x'])}, {vec(r['y'])}, {vec(r['z'])}, {f(r['housed'])}, {f(r['run_in'])}, {f(r['run_out'])}, "
            f"{f(r['slide'])}, {f(r['elev'])}, {f(r['lid'])}, {f(r['lo'])}, {f(r['hi'])});")
        h = r.get("hinge")
        if h:
            lines.append(f"Hinge({vec(h['origin_m'])}, {vec(h['x'])}, {vec(h['y'])}, {vec(h['z'])});")
    with open(out_path, "w", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("build", help="a build directory holding guns.json, or the file")
    ap.add_argument("--out", default=DEFAULT_OUT)
    a = ap.parse_args(argv)
    path = os.path.join(a.build, "guns.json") if os.path.isdir(a.build) else a.build
    with open(path) as fh:
        guns = json.load(fh)
    rs = rows(guns)
    # Sanity: every gun recoils inboard of its run-out place and its axes are unit and square.
    for r in rs:
        assert r["run_in"] < r["run_out"], r["id"]
        for k in ("x", "y", "z"):
            n = sum(c * c for c in r[k]) ** 0.5
            assert abs(n - 1.0) < 1e-3, (r["id"], k, n)
    write(rs, a.out, os.path.basename(os.path.dirname(os.path.abspath(path))) + "/guns.json")
    print(f"{len(rs)} guns -> {os.path.relpath(a.out, REPO)}")


if __name__ == "__main__":
    main(sys.argv[1:])
