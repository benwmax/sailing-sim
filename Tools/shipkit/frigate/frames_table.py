"""Write the frigate's moving gun-deck parts for the game (docs/ship-frames/).

    python3 -I Tools/shipkit/frigate/frames_table.py <build dir with gundeck.json> \
        Source/SailingPhysics/Private/CommonwealthFramesData.inl

gundeck.json (the tiller build, docs/frigate-tiller) holds `frames` (each moving part's pivot and axes in the ship,
as built with the helm amidships), `tiller` (hard over), `tiller_ropes` (`poses`: the six rope parts' frames for every
whole degree of helm, `wheel_turns`) and `cabin_doors` (the swing's sign and angle); deck.json's `frames` are the spar
deck's wheel and capstan (origin, `axes`). The .inl is generated: edit this script or the build, never the .inl.
"""
import json
import os
import sys

ROPE_PARTS = ['TillerEye_S', 'TillerRun_S', 'TillerWrap_S', 'TillerEye_P', 'TillerRun_P', 'TillerWrap_P']
KINDS = {'Tiller': 'Tiller', 'GunCapstan': 'Capstan', 'Capstan': 'Capstan', 'Wheel': 'Wheel'}
BELOW = set(['Tiller', 'GunCapstan', 'CabinDoor_S', 'CabinDoor_P'] + ROPE_PARTS)   # the gun deck's parts (exported under Decks/); the rest under Outside/


def num(v):
    s = repr(round(float(v), 6))
    return s if ('.' in s or 'e' in s) else s + '.0'


def vec(v):
    return '{ %s, %s, %s }' % tuple(num(x) for x in v)


def mat(r):
    return '{ %s }' % ', '.join('{ %s }' % ', '.join(num(x) for x in row) for row in r)


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    build, out = sys.argv[1], sys.argv[2]
    with open(os.path.join(build, 'gundeck.json')) as f:
        d = json.load(f)
    frames = dict(d['frames'])
    with open(os.path.join(build, 'deck.json')) as f:
        for name, fr in json.load(f)['frames'].items():
            frames[name] = {'origin_m': fr['origin_m'], 'x': fr['axes'][0], 'y': fr['axes'][1], 'z': fr['axes'][2]}
    doors = d['cabin_doors']
    ropes = d['tiller_ropes']
    lines = ['// Generated by Tools/shipkit/frigate/frames_table.py from the frigate build\'s gundeck.json: do not edit.',
             '// The frigate Commonwealth\'s moving parts (docs/ship-frames/): each part\'s pivot and axes in the ship frame (m, helm',
             '// amidships), the tiller ropes\' poses by the helm\'s degree, the cabin doors\' swing, the wheel and the capstans.',
             'namespace Sailing', '{', 'namespace CommonwealthFramesTable', '{',
             'constexpr double kHardOverDeg = %s;' % num(d['tiller']['hard_over_deg']),
             'constexpr double kWheelTurnsHardOver = %s;' % num(abs(ropes['wheel_turns'][str(int(d['tiller']['hard_over_deg']))])),
             'constexpr double kDoorOpenDeg = %s;' % num(next(iter(doors.values()))['open_deg']),
             'static const FShipFrame kFrames[] = {']
    order = ['Tiller'] + ROPE_PARTS + sorted(doors.keys()) + ['GunCapstan', 'Wheel', 'Capstan']
    for name in order:
        fr = frames[name]
        if name in ROPE_PARTS:
            kind, sign, rope = 'Rope', 0.0, ROPE_PARTS.index(name)
        elif name in doors:
            kind, sign, rope = 'Door', doors[name]['open_sign'], -1
        else:
            kind, sign, rope = KINDS[name], 0.0, -1
        below = 'true' if name in BELOW else 'false'
        lines.append('\t{ "%s", EShipFrameKind::%s, %s, %s, %s, %s, %s, %d, %s },'
                     % (name, kind, vec(fr['origin_m']), vec(fr['x']), vec(fr['y']), vec(fr['z']), num(sign), rope, below))
    lines.append('};')
    lines.append('static const FRopePoseRow kPoses[] = {')
    poses = sorted(ropes['poses'], key=lambda p: p['helm_deg'])
    for p in poses:
        parts = []
        for name in ROPE_PARTS:
            q = p[name]
            parts.append('{ %s, %s, %s }' % (vec(q['o']), mat(q['R']), num(q.get('scale_x', 1.0))))
        lines.append('\t{ %s, { %s } },' % (num(p['helm_deg']), ', '.join(parts)))
    lines.append('};')
    lines += ['}', '}', '']
    with open(out, 'w') as f:
        f.write('\n'.join(lines))
    print('%s: %d frames, %d pose rows' % (out, len(order), len(poses)))


if __name__ == '__main__':
    main()
