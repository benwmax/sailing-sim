"""Writes Source/SailingPhysics/Private/J22HullData.inl: the J/22's half sections for the physics, taken from the hero
model's own hull formula (Inputs/j22-hero/build_j22_hero.py: keel_z, sheer_z, half_beam, section), so the boat the
simulation floats is the boat the player sees (Bean, Nov 10 2026: the underwater bow follows the class drawing,
docs/shape-loop).

    python3 Tools/boats/j22/make_j22_hull.py            # write the table
    python3 Tools/boats/j22/make_j22_hull.py --check    # exit 1 if the table in git no longer matches the build script

Plain Python: it reads the build script's "principal numbers" and hull functions as text and runs only those (no
Blender). Prints the canoe volume and centre of buoyancy below the DWL by the build's own integration
(hull_volume_below), the numbers the hero's j22_hero_report.json checks.
"""
import math
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", ".."))
SRC = os.path.join(ROOT, "Inputs", "j22-hero", "build_j22_hero.py")
OUT = os.path.join(ROOT, "Source", "SailingPhysics", "Private", "J22HullData.inl")
N_STATIONS, N_POINTS = 41, 15

text = open(SRC).read()
a = text.index("BOW, STERN = ")
b = text.index("def stations(n):")
c = text.index("def hull_volume_below(")
d = text.index("# ------------------------------------------------------------------ deck mould")
ns = {"math": math}
exec(text[a:b], ns)                    # the principal numbers, keel_z, sheer_z, half_beam, section
exec(text[c:d], ns)                    # hull_volume_below
BOW, STERN, section, sheer_z = ns["BOW"], ns["STERN"], ns["section"], ns["sheer_z"]


def girth_fractions(n):
    """Closer together near the keel, where the section turns fastest."""
    return [1 - math.cos(0.5 * math.pi * k / (n - 1)) for k in range(n)]


rows = []
for i in range(N_STATIONS):
    t = i / (N_STATIONS - 1)
    x = STERN + (BOW - STERN) * t
    ys, zs = [], []
    for f in girth_fractions(N_POINTS):
        y, z = section(x, min(f, 1.0))
        ys.append(max(y, ys[-1] if ys else 0.0))       # half breadths never decrease (the physics reads them so)
        zs.append(z)
    ys[0] = 0.0
    rows.append((x, sheer_z(x), ys, zs))

vol, cbx, cbz = ns["hull_volume_below"](0.0)


def num(v):
    return f"{v:.4f}".rstrip("0").rstrip(".") if v else "0"


L = []
L.append("// Generated by Tools/boats/j22/make_j22_hull.py from Inputs/j22-hero/build_j22_hero.py: do not edit.\n")
L.append("// The J/22's half sections, transom to stem: body frame metres (X forward, Y starboard, Z up, origin on the DWL\n")
L.append("// amidships), each from the keel (Y 0) to the sheer, half breadths never decreasing. The hero model's hull.\n")
L.append(f"// Hero canoe volume {vol:.4f} m^3 below the DWL, centre of buoyancy x {cbx:.3f} z {cbz:.3f}.\n\n")
L.append(f"constexpr int kJ22Stations = {N_STATIONS};\n")
L.append(f"constexpr int kJ22SectionPoints = {N_POINTS};\n")
L.append(f"constexpr double kJ22CanoeVolume = {vol:.4f};\n")
L.append("\nstruct FJ22Section { double X, Sheer; double Y[kJ22SectionPoints], Z[kJ22SectionPoints]; };\n")
L.append("const FJ22Section kJ22Sections[kJ22Stations] = {\n")
for x, sh, ys, zs in rows:
    L.append(f"\t{{ {num(x)}, {num(sh)}, {{ {', '.join(num(v) for v in ys)} }}, {{ {', '.join(num(v) for v in zs)} }} }},\n")
L.append("};\n")
text_out = "".join(L)
if "--check" in sys.argv:
    have = open(OUT).read() if os.path.exists(OUT) else ""
    if have != text_out:
        sys.exit(f"make_j22_hull: {OUT} is stale: the build script's hull changed; run Tools/boats/j22/make_j22_hull.py")
    print(f"make_j22_hull: {OUT} matches the build script")
    sys.exit(0)
with open(OUT, "w") as f:
    f.write(text_out)
print(f"make_j22_hull: {OUT}: {N_STATIONS} stations x {N_POINTS} points; hero canoe volume {vol:.4f} m^3, CB x {cbx:.3f} z {cbz:.3f}")
