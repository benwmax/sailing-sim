"""Boat fidelity 4: writes Source/SailingSim/Private/J22CoilData.inl from Inputs/j22-hero/J22H_coils.json, the hero J/22's
coiled tails (written by build_j22_hero.py; J22H_COILS_ONLY=1 skips its sail maps), so BoatModelVisuals.cpp draws them as
live rope on their baked shadows. Edit the hero script or this, never the .inl.

    python3 Tools/boats/make_coil_data.py
"""
import json
import os

REPO = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
SRC = os.path.join(REPO, "Inputs", "j22-hero", "J22H_coils.json")
OUT = os.path.join(REPO, "Source", "SailingSim", "Private", "J22CoilData.inl")
# The hero's rope materials -> RopeLook rows (Inputs/rope/colourways.json order).
LOOKS = {"RopeMain": 0, "RopeJibPort": 1, "RopeJibStbd": 2, "RopeHalyard": 4}


def main():
    coils = json.load(open(SRC))["coils"]
    lines = ["// Generated by Tools/boats/make_coil_data.py from Inputs/j22-hero/J22H_coils.json: do not edit.",
             "// The hero J/22's coiled tails in the boat frame (cm; Blender's Y flipped), drawn by UpdateModelRig.", ""]
    pts = []
    starts = []
    for c in coils:
        starts.append((c["name"], len(pts), len(c["points_m"]), c["radius_m"] * 100.0, LOOKS.get(c["material"], 0)))
        pts += [(p[0] * 100.0, -p[1] * 100.0, p[2] * 100.0) for p in c["points_m"]]
    lines.append(f"static const float GJ22CoilPoints[{len(pts)}][3] = {{")
    for p in pts:
        lines.append(f"\t{{ {p[0]:.3f}f, {p[1]:.3f}f, {p[2]:.3f}f }},")
    lines.append("};")
    lines.append("struct FJ22Coil { const TCHAR* Name; int32 First, Count; float RadiusCm; uint8 Look; };")
    lines.append(f"static const FJ22Coil GJ22Coils[{len(starts)}] = {{")
    for name, first, count, r, look in starts:
        lines.append(f"\t{{ TEXT(\"{name}\"), {first}, {count}, {r:.3f}f, {look} }},")
    lines.append("};")
    open(OUT, "w", newline="\n").write("\n".join(lines) + "\n")
    print(f"{len(starts)} coils, {len(pts)} points -> {OUT}")


if __name__ == "__main__":
    main()
