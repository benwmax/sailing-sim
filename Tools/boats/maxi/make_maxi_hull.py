"""Writes Source/SailingPhysics/Private/MaxiHullData.inl from the PC's exported hull (sections.json) and reference sheet
(ref.json): the maxi's physics hull is these sections, so the physics floats, heels and drags on the model's own shape.

Run: python3 Tools/boats/maxi/make_maxi_hull.py   (edit the JSON or this script, never the .inl)

The two JSON files are copies of the PC's maxi-hero branch (Tools/boats/maxi/ref.json and sections.json, commit
f8b22240); when the PC re-exports, copy them over and rerun this. It also prints the appendage volumes the physics adds
as fixed buoyancy (keel fin, bulb, rudders: the canoe body is the sections) and the parametric stand-in fit that the
water's hull clip and BoatExport use.
"""
import json
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
OUT = os.path.join(ROOT, "Source", "SailingPhysics", "Private", "MaxiHullData.inl")

REF = json.load(open(os.path.join(HERE, "ref.json")))
SEC = json.load(open(os.path.join(HERE, "sections.json")))


def fmt(v):
    return ("%.4f" % v).rstrip("0").rstrip(".") if abs(v) > 1e-9 else "0"


def appendages():
    """Volumes (m^3) and centroids (x, z) of the fin, bulb and one rudder, from ref.json's plan forms.

    Sections are NACA 00xx-like: a symmetric foil's area is 0.685 x chord x thickness. The bulb is a body of revolution
    with a prismatic coefficient of 0.62 (torpedo bulbs run 0.6-0.65). The fin runs from the canoe body's bottom under
    the keel's root to the bulb's top."""
    k = REF["keel"]
    bulb_r = 0.5 * k["bulb_diameter"]
    bulb_v = 0.62 * math.pi * bulb_r * bulb_r * k["bulb_length"]
    bulb_x = k["bulb_x_nose"] - 0.45 * k["bulb_length"]
    bulb_z = -k["draft"] + bulb_r
    root_z = -0.95  # the canoe body's bottom at the keel root (sections.json: -0.94 to -0.95 there)
    tip_z = -k["draft"] + 2.0 * bulb_r * 0.85  # the fin enters the bulb a little below its top
    span = root_z - tip_z
    tc = k["thickness"] / k["root_chord"]  # the thickness is the root's; the tip keeps the same t/c
    area_root = 0.685 * k["root_chord"] * k["thickness"]
    area_tip = 0.685 * k["tip_chord"] * k["tip_chord"] * tc
    fin_v = span * (area_root + area_tip + math.sqrt(area_root * area_tip)) / 3.0
    fin_x = k["x_root_le"] - 0.45 * (0.5 * (k["root_chord"] + k["tip_chord"])) - 0.5 * span * math.tan(math.radians(k["sweep_deg"]))
    fin_z = 0.5 * (root_z + tip_z)
    r = REF["rudders"]
    rtc = r["thickness"] / r["root_chord"]
    rud_v = r["span"] * 0.685 * rtc * (r["root_chord"] ** 2 + r["root_chord"] * r["tip_chord"] + r["tip_chord"] ** 2) / 3.0
    return {"fin": (fin_v, fin_x, fin_z, span), "bulb": (bulb_v, bulb_x, bulb_z), "rudder": (rud_v,)}


def canoe_from_sections():
    """Volume and centre of buoyancy at the DWL from the sections (trapezoids), to compare with the export's own."""
    sts = SEC["stations"]
    areas, zc = [], []
    for s in sts:
        a = m = 0.0
        pts = s["half_section"]
        for (y0, z0), (y1, z1) in zip(pts, pts[1:]):
            z0c, z1c = min(z0, 0.0), min(z1, 0.0)
            seg = 0.5 * (-z0c - z1c) * (y1 - y0)
            a += seg
            m += seg * 0.25 * (z0c + z1c)
        areas.append(2.0 * a)
        zc.append(m / a if a > 0 else 0.0)
    v = mx = mz = 0.0
    for i in range(len(sts) - 1):
        dx = sts[i + 1]["x"] - sts[i]["x"]
        seg = 0.5 * (areas[i] + areas[i + 1]) * dx
        v += seg
        mx += seg * 0.5 * (sts[i]["x"] + sts[i + 1]["x"])
        mz += 0.5 * (areas[i] * zc[i] + areas[i + 1] * zc[i + 1]) * dx
    return v, mx / v, mz / v


def main():
    sts = SEC["stations"]
    npts = len(sts[0]["half_section"])
    assert all(len(s["half_section"]) == npts for s in sts), "every section needs the same point count"
    for s in sts:
        ys = [p[0] for p in s["half_section"]]
        assert all(b >= a for a, b in zip(ys, ys[1:])), "half breadths must not decrease keel to sheer"
    v, cbx, cbz = canoe_from_sections()
    app = appendages()
    lines = [
        "// Generated by Tools/boats/maxi/make_maxi_hull.py from Tools/boats/maxi/sections.json (the PC's export): do not edit.",
        "// The maxi's half sections, transom to stem: body frame metres (X forward, Y starboard, Z up, origin on the DWL",
        "// amidships), each from the keel (Y 0) to the sheer, half breadths never decreasing.",
        "// Export: canoe volume %.2f m^3, centre of buoyancy x %.3f z %.3f (trapezoids here: %.2f m^3, x %.3f, z %.3f)."
        % (SEC["canoe_volume_m3"], SEC["centre_of_buoyancy"][0], SEC["centre_of_buoyancy"][1], v, cbx, cbz),
        "",
        "constexpr int kMaxiStations = %d;" % len(sts),
        "constexpr int kMaxiSectionPoints = %d;" % npts,
        "constexpr double kMaxiCanoeVolume = %s;   // m^3 at the DWL, sections.json" % fmt(SEC["canoe_volume_m3"]),
        "constexpr double kMaxiBuoyancyX = %s;     // sections.json centre_of_buoyancy" % fmt(SEC["centre_of_buoyancy"][0]),
        "constexpr double kMaxiBuoyancyZ = %s;" % fmt(SEC["centre_of_buoyancy"][1]),
        "constexpr double kMaxiCanoeDepth = %s;    // ref.json canoe_depth" % fmt(REF["canoe_depth"]),
        "// Appendages from ref.json's plan forms (fixed buoyancy in the physics): fin, bulb, one rudder (m^3; x, z).",
        "constexpr double kMaxiFinVolume = %s; constexpr double kMaxiFinX = %s; constexpr double kMaxiFinZ = %s;"
        % (fmt(app["fin"][0]), fmt(app["fin"][1]), fmt(app["fin"][2])),
        "constexpr double kMaxiBulbVolume = %s; constexpr double kMaxiBulbX = %s; constexpr double kMaxiBulbZ = %s;"
        % (fmt(app["bulb"][0]), fmt(app["bulb"][1]), fmt(app["bulb"][2])),
        "constexpr double kMaxiRudderVolume = %s;" % fmt(app["rudder"][0]),
        "",
        "struct FMaxiSection { double X, Sheer; double Y[kMaxiSectionPoints], Z[kMaxiSectionPoints]; };",
        "const FMaxiSection kMaxiSections[kMaxiStations] = {",
    ]
    for s in sts:
        ys = ", ".join(fmt(p[0]) for p in s["half_section"])
        zs = ", ".join(fmt(p[1]) for p in s["half_section"])
        lines.append("\t{ %s, %s, { %s }, { %s } }," % (fmt(s["x"]), fmt(s["sheer"]), ys, zs))
    lines.append("};")
    with open(OUT, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", os.path.relpath(OUT, ROOT))
    print("canoe (trapezoids) %.3f m^3, CB x %.3f z %.3f; export %.2f, %s" % (v, cbx, cbz, SEC["canoe_volume_m3"], SEC["centre_of_buoyancy"]))
    tot = app["fin"][0] + app["bulb"][0] + 2 * app["rudder"][0]
    print("fin %.3f m^3 (span %.2f m) bulb %.3f rudders 2 x %.3f: appendages %.3f m^3; with the canoe %.2f m^3 (ref displacement %.0f kg)"
          % (app["fin"][0], app["fin"][3], app["bulb"][0], app["rudder"][0], tot, SEC["canoe_volume_m3"] + tot, REF["displacement_kg"]))


if __name__ == "__main__":
    main()
