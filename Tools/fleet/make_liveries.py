"""Graphics G3: turns the boat catalogue (Inputs/g3/boat-catalogue.json, sourced colour schemes and wear per class) into
Source/SailingSim/Private/BoatLiveryData.inl, the table FBoatLivery samples from (BoatLivery.h). Hex colours become
linear RGB; each class's wear zones collapse into four channels by kind (oxidation; stain = the waterline scum; scuff;
rust), each with a [min, max] intensity per profile (club, race, charter), and the coloured sails' sun fade (kind "fade",
FLiveryWear::FadeRange) the same way. A class's "spars" "finishes" (pc/j22-detail: weight, hex, painted or anodised)
become FLiverySpar rows; a class without them keeps its mast material's own aluminium.
    python3 Tools/fleet/make_liveries.py [catalogue.json] [out.inl]
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "Inputs", "g3", "boat-catalogue.json")
OUT = sys.argv[2] if len(sys.argv) > 2 else os.path.join(ROOT, "Source", "SailingSim", "Private", "BoatLiveryData.inl")
ORDER = ["j22", "sunfish", "ilca7", "catalina22", "catalina30", "hobie16", "corsair880", "lagoon42", "maxi"]   # EBoatType order
CHANNELS = {"oxidation": 0, "stain": 1, "scuff": 2, "rust": 3}


def lin(h):
    h = h.lstrip("#")
    c = [int(h[i:i + 2], 16) / 255.0 for i in (0, 2, 4)]
    return [x / 12.92 if x <= 0.04045 else ((x + 0.055) / 1.055) ** 2.4 for x in c]


def col(h, fallback):
    if not h or not isinstance(h, str) or not h.startswith("#"):
        h = fallback
    r, g, b = lin(h)
    return f"FLinearColor({r:.4f}f, {g:.4f}f, {b:.4f}f)"


# Graphics G6: what Bean's lesson photos show on the Rush Creek club J/22s (the commonest scheme): non-skid aged to a
# beige with grime in its pattern, not the catalogue's factory grey, and the smooth deck a little cream.
OVERRIDES = {("j22", "white_factory_teak"): {"nonskid_hex": "#C8BB9C", "deck_hex": "#EDE8DC"}}


def main():
    cat = json.load(open(SRC))
    by = {c["id"]: c for c in cat["classes"]}
    for (cid, sid), o in OVERRIDES.items():
        for sc in by[cid]["colour_schemes"]:
            if sc["id"] == sid:
                sc.update(o)
    lines = ["// Generated by Tools/fleet/make_liveries.py from Inputs/g3/boat-catalogue.json. Do not edit.",
             "// Per class: colour schemes (weight, hull, deck, non-skid, bottom, boot, cove, sheer, teak trim, teak) and wear",
             "// ranges per profile for oxidation, waterline scum, scuffs and rust; spar finishes (weight, colour, painted).", ""]
    for cid in ORDER:
        c = by[cid]
        lines.append(f"static const FLiveryScheme Schemes_{cid}[] = {{")
        for s in c["colour_schemes"]:
            hull = s.get("hull_hex") or (s.get("hull_hex_options") or ["#F2F0EA"])[0]
            stripes = [(st["zone"], st["hex"]) for st in s.get("stripes", []) if isinstance(st.get("hex"), str) and st["hex"].startswith("#")]
            # The models' stripe slots: Bootstripe (boot, waterline), CoveStripe (cove, sheer).
            boot = next((h for z, h in stripes if z.startswith("boot") or "waterline" in z), None)
            cove = next((h for z, h in stripes if "cove" in z), None) or next((h for z, h in stripes if "sheer" in z), None)
            sheer = next((h for z, h in stripes if "sheer" in z), None)
            trim = s.get("trim", {}) or {}
            teak = "teak" in str(trim.get("handrails", "")) or "teak" in str(trim.get("toerail", ""))
            lines.append(f"\t{{ {s['weight']:.3f}f, {col(hull, '#F2F0EA')}, {col(s.get('deck_hex'), hull)}, "
                         f"{col(s.get('nonskid_hex'), s.get('deck_hex') or hull)}, {col(s.get('bottom_hex'), '#6E6A5E')}, "
                         f"{'true' if boot else 'false'}, {col(boot, '#1C2A44')}, {'true' if cove else 'false'}, {col(cove, '#1C2A44')}, "
                         f"{'true' if sheer else 'false'}, {col(sheer, '#1C2A44')}, {'true' if teak else 'false'}, {col(trim.get('teak_hex'), '#8C8478')} }}, // {s['id']}")
        lines.append("};")
        w = c["wear"]
        prof = w["profile_weights"]
        ranges = {p: [[0.0, 0.0] for _ in CHANNELS] for p in ("club", "race", "charter")}
        for z in w["zones"]:
            ch = CHANNELS.get(z["kind"])
            if ch is None:
                continue
            for p, rng in z["intensity"].items():
                if p in ranges:
                    ranges[p][ch] = [max(ranges[p][ch][0], rng[0]), max(ranges[p][ch][1], rng[1])]
        fade = {p: [0.0, 0.0] for p in ("club", "race", "charter")}
        for z in w["zones"]:
            if z["kind"] == "fade":
                for p, rng in z["intensity"].items():
                    if p in fade:
                        fade[p] = [max(fade[p][0], rng[0]), max(fade[p][1], rng[1])]

        def r4(p):
            return "{ " + ", ".join(f"{{ {a:.2f}f, {b:.2f}f }}" for a, b in ranges[p]) + " }"
        f3 = "{ " + ", ".join(f"{{ {fade[p][0]:.2f}f, {fade[p][1]:.2f}f }}" for p in ("club", "race", "charter")) + " }"
        lines.append(f"static const FLiveryWear Wear_{cid} = {{ {prof.get('club', 0):.2f}f, {prof.get('race', 0):.2f}f, {prof.get('charter', 0):.2f}f, "
                     f"{r4('club')}, {r4('race')}, {r4('charter')}, {f3} }};")
        sn = c["sail_number"]
        rng = sn.get("number_range", [1, 999])
        lines.append(f"static const FLiveryNumbers Numbers_{cid} = {{ {'true' if sn.get('required') else 'false'}, {float(sn.get('probability', 1.0 if sn.get('required') else 0.0)):.2f}f, "
                     f"{rng[0]}, {rng[1]}, TEXT(\"{sn.get('format', '{n}')}\") }};")
        finishes = (c.get("spars") or {}).get("finishes", [])
        if finishes:
            lines.append(f"static const FLiverySpar Spars_{cid}[] = {{")
            for s in finishes:
                lines.append(f"\t{{ {s['weight']:.3f}f, {col(s['hex'], '#C9CCCF')}, {'true' if s['finish'] == 'painted' else 'false'} }}, // {s['id']}")
            lines.append("};")
        lines.append("")
    lines.append("static const FLiveryClass LiveryClasses[] = {")
    for cid in ORDER:
        spars = f"Spars_{cid}, UE_ARRAY_COUNT(Spars_{cid})" if (by[cid].get("spars") or {}).get("finishes") else "nullptr, 0"
        lines.append(f"\t{{ Schemes_{cid}, UE_ARRAY_COUNT(Schemes_{cid}), &Wear_{cid}, &Numbers_{cid}, {spars} }},")
    lines.append("};")
    open(OUT, "w").write("\n".join(lines) + "\n")
    print("wrote", OUT)


main()
