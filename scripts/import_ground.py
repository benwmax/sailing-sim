"""Shore plan Track A (docs/envloop/ground): the textured ground. Imports the eight prepared ground scans as three
Texture2DArrays and builds M_Ground, the layered ground material the terrain's chunks use on Medium and up
(ALakeTerrainActor::ChunkMaterial; Low and the garrigue keep M_Terrain, -SailingClassicGround compares).

Run in the editor after make_materials.py (MPC_World must exist), with the prepared maps on disk:

    python3 -I Tools/envloop/ground/fetch_ground.py            # the CC0 scans, about 200 MB (git-ignored)
    python3 -I Tools/envloop/ground/prep_ground.py --res 2048  # calibrated maps (needs scipy and Pillow)
    Mac:  "$UE_ROOT/Engine/Binaries/Mac/UnrealEditor-Cmd" SailingSim.uproject -run=pythonscript -script=scripts/import_ground.py -unattended -nosplash -nosound -NoP4 -stdout
    PC:   scripts\\windows\\run-python.ps1 import_ground.py

What it makes:
  /Game/Materials/Ground/Slices/T_Ground_<surface>_{A,N,R}   the eight surfaces' colour (sRGB), normal (BC5) and RHA
                                                            (roughness, height, AO; linear) at GROUND_RES (2048)
  /Game/Materials/Ground/TA_Ground_{Albedo,Normal,RHA}        the three 8-slice arrays, in the region pack's role order
  /Game/Materials/M_Ground                                    the material: Tools/envloop/ground/M_Ground.hlsl in one
                                                            Custom node (generated by ground_hlsl.py from the pack; the
                                                            editor's Python has no numpy, so the committed copy is read)
  MPC_World.Season                                            0 summer .. 1 dormant (ASailingEnvironment sets it)

Cost (the Mac's world gate): 12 texture fetches a pixel inside 35 m, 6 to 75 m (no second scale), 2 to 150 m (colour
only), none past it; the normal and RHA arrays are trilinear, the colour anisotropic; ray-traced hits read no texture.

Environment: GROUND_PACK (default north-texas-lake), GROUND_RES (2048; the tiers below read smaller mips through the
texture group's LOD bias), GROUND_MATERIAL_ONLY=1 rebuilds M_Ground without reimporting the textures.
"""
import os

import unreal

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PACK = os.environ.get("GROUND_PACK", "north-texas-lake")
RES = int(os.environ.get("GROUND_RES", "2048"))
PREP = os.path.join(REPO, "Data", "Ground", "prep", PACK)
HLSL = os.path.join(REPO, "Tools", "envloop", "ground", "M_Ground.hlsl")
MATERIALS = "/Game/Materials"
GROUND = "/Game/Materials/Ground"
SLICES = GROUND + "/Slices"
ASSETS = unreal.AssetToolsHelpers.get_asset_tools()
MEL = unreal.MaterialEditingLibrary
LIB = unreal.EditorAssetLibrary
# The pack's role order (Tools/envloop/ground/pack.py ROLES): slice k of every array is this surface.
ROLES = ["lawn", "rough", "clay", "gravel", "sand", "mud", "cracked", "litter"]
MAPS = {"A": ("albedo", True), "N": ("normal", False), "R": ("rha", False)}   # suffix: (prep file, sRGB)


def import_slice(role, suffix):
    stem, srgb = MAPS[suffix]
    src = os.path.join(PREP, f"{role}_{RES}_{stem}.png")
    if not os.path.exists(src):
        raise FileNotFoundError(f"{src}: run fetch_ground.py and prep_ground.py --res {RES} first")
    name = f"T_Ground_{role}_{suffix}"
    task = unreal.AssetImportTask()
    task.set_editor_property("filename", src)
    task.set_editor_property("destination_path", SLICES)
    task.set_editor_property("destination_name", name)
    task.set_editor_property("automated", True)
    task.set_editor_property("replace_existing", True)
    task.set_editor_property("save", False)
    ASSETS.import_asset_tasks([task])
    tex = unreal.load_asset(f"{SLICES}/{name}")
    if tex is None:
        raise RuntimeError(f"import of {src} failed")
    tex.set_editor_property("srgb", srgb)
    tex.set_editor_property("lod_group", unreal.TextureGroup.TEXTUREGROUP_WORLD)
    if suffix == "N":
        # The prep keeps the scans' OpenGL convention (+Y up), the same data the numpy twin rendered: no green flip.
        tex.set_editor_property("compression_settings", unreal.TextureCompressionSettings.TC_NORMALMAP)
        tex.set_editor_property("flip_green_channel", False)
    elif suffix == "R":
        tex.set_editor_property("compression_settings", unreal.TextureCompressionSettings.TC_MASKS)
    else:
        tex.set_editor_property("compression_settings", unreal.TextureCompressionSettings.TC_DEFAULT)
    LIB.save_loaded_asset(tex)
    return tex


def make_array(name, slices, srgb, compression):
    """An 8-slice Texture2DArray from the imported slices, rebuilt in place when it exists (M_Ground references it)."""
    path = f"{GROUND}/{name}"
    arr = unreal.load_asset(path) if LIB.does_asset_exist(path) else None
    if arr is None:
        factory = unreal.Texture2DArrayFactory()
        try:
            factory.set_editor_property("initial_textures", slices)
        except Exception as e:   # older bindings: the factory makes an empty array and the slices go in below
            unreal.log_warning(f"Texture2DArrayFactory has no initial_textures ({e}); setting source_textures instead")
        arr = ASSETS.create_asset(name, GROUND, unreal.Texture2DArray, factory)
    arr.set_editor_property("source_textures", slices)
    if hasattr(arr, "update_source_from_source_textures"):
        arr.update_source_from_source_textures()
    arr.set_editor_property("srgb", srgb)
    arr.set_editor_property("compression_settings", compression)
    arr.set_editor_property("lod_group", unreal.TextureGroup.TEXTUREGROUP_WORLD)
    arr.set_editor_property("address_x", unreal.TextureAddress.TA_WRAP)
    arr.set_editor_property("address_y", unreal.TextureAddress.TA_WRAP)
    # The ground is always seen at a grazing angle, so anisotropic filtering runs its full tap count on every fetch. The
    # colour keeps it (the sand's grain and the lawn's blades at 15 m); the normal and RHA arrays, whose detail is not
    # legible at those angles, are trilinear (one tap set each: the world gate's cost cut).
    arr.set_editor_property("filter", unreal.TextureFilter.TF_DEFAULT if srgb else unreal.TextureFilter.TF_TRILINEAR)
    LIB.save_loaded_asset(arr)
    return arr


def world_collection():
    mpc = unreal.load_asset("/Game/World/MPC_World")
    if mpc is None:
        raise RuntimeError("MPC_World missing: run make_materials.py first")
    scalars = list(mpc.get_editor_property("scalar_parameters"))
    added = False
    for name, default in (("Season", 0.0), ("GroundDetail", 1.0)):
        if any(str(x.get_editor_property("parameter_name")) == name for x in scalars):
            continue
        s = unreal.CollectionScalarParameter()
        s.set_editor_property("parameter_name", name)
        s.set_editor_property("default_value", default)
        scalars.append(s)
        added = True
    if added:
        mpc.set_editor_property("scalar_parameters", scalars)
        LIB.save_loaded_asset(mpc)
    return mpc


MAP_FRAME_POSITIONS = ("MaterialExpressionWorldPosition", "MaterialExpressionCameraPositionWS")


def node(mat, cls, x, y, **props):
    """As make_materials.py's node(): world and camera positions get MPC_World.RenderOrigin added (the map frame)."""
    n = MEL.create_material_expression(mat, cls, x, y)
    for k, v in props.items():
        n.set_editor_property(k, v)
    if cls.__name__ in MAP_FRAME_POSITIONS:
        origin = MEL.create_material_expression(mat, unreal.MaterialExpressionCollectionParameter, x - 220, y + 40)
        origin.set_editor_property("collection", world_collection())
        origin.set_editor_property("parameter_name", "RenderOrigin")
        mask = MEL.create_material_expression(mat, unreal.MaterialExpressionComponentMask, x - 120, y + 40)
        for c, on in (("r", True), ("g", True), ("b", True), ("a", False)):
            mask.set_editor_property(c, on)
        MEL.connect_material_expressions(origin, "", mask, "")
        add = MEL.create_material_expression(mat, unreal.MaterialExpressionAdd, x + 120, y)
        MEL.connect_material_expressions(n, "", add, "A")
        MEL.connect_material_expressions(mask, "", add, "B")
        return add
    return n


def connect(a, a_out, b, b_in):
    if not MEL.connect_material_expressions(a, a_out, b, b_in):
        raise RuntimeError(f"connect failed: {a.get_name()}.{a_out} -> {b.get_name()}.{b_in}")


def collection_param(mat, name, x, y):
    p = node(mat, unreal.MaterialExpressionCollectionParameter, x, y)
    p.set_editor_property("collection", world_collection())
    p.set_editor_property("parameter_name", name)
    return p


def custom(mat, code, inputs, x, y, extra_outputs):
    c = node(mat, unreal.MaterialExpressionCustom, x, y)
    c.set_editor_property("code", code)
    c.set_editor_property("output_type", unreal.CustomMaterialOutputType.CMOT_FLOAT3)
    ins = []
    for name in inputs:
        i = unreal.CustomInput()
        i.set_editor_property("input_name", name)
        ins.append(i)
    c.set_editor_property("inputs", ins)
    outs = []
    for name, kind in extra_outputs:
        o = unreal.CustomOutput()
        o.set_editor_property("output_name", name)
        o.set_editor_property("output_type", kind)
        outs.append(o)
    c.set_editor_property("additional_outputs", outs)
    return c


CURVATURE_CODE = """
float2 d = (WP - Cam).xy;
return float3(0.0, 0.0, -dot(d, d) / (2.0 * 7.433e8));
"""


def build_material(arrays):
    """M_Ground: the generated HLSL in one Custom node over the terrain's vertex colour, world position, normal, the
    water height, the camera, the Mown UV and the season; the earth's curvature as M_Terrain's WPO."""
    path = f"{MATERIALS}/M_Ground"
    if LIB.does_asset_exist(path):
        LIB.delete_asset(path)
    mat = ASSETS.create_asset("M_Ground", MATERIALS, unreal.Material, unreal.MaterialFactoryNew())
    # The terrain's procedural mesh has no tangents: the node outputs a world-space normal.
    mat.set_editor_property("tangent_space_normal", False)
    code = open(HLSL).read()
    f1, f3 = unreal.CustomMaterialOutputType.CMOT_FLOAT1, unreal.CustomMaterialOutputType.CMOT_FLOAT3
    c = custom(mat, code, ["P", "N", "C", "CA", "WaterZ", "Cam", "Mown", "Season", "Detail", "Alb", "Nrm", "Rha"], -300, 0,
               [("Rough", f1), ("WN", f3), ("AO", f1)])
    connect(node(mat, unreal.MaterialExpressionWorldPosition, -1100, -200), "", c, "P")
    connect(node(mat, unreal.MaterialExpressionVertexNormalWS, -1100, -80), "", c, "N")
    vc = node(mat, unreal.MaterialExpressionVertexColor, -1100, 0)
    connect(vc, "", c, "C")
    connect(vc, "A", c, "CA")
    connect(collection_param(mat, "WaterZ", -1100, 120), "", c, "WaterZ")
    connect(node(mat, unreal.MaterialExpressionCameraPositionWS, -1100, 220), "", c, "Cam")
    uv = node(mat, unreal.MaterialExpressionTextureCoordinate, -1300, 340, coordinate_index=0)
    mown = node(mat, unreal.MaterialExpressionComponentMask, -1100, 340, r=True, g=False, b=False, a=False)
    connect(uv, "", mown, "")
    connect(mown, "", c, "Mown")
    connect(collection_param(mat, "Season", -1100, 440), "", c, "Season")
    connect(collection_param(mat, "GroundDetail", -1100, 500), "", c, "Detail")
    for k, (pin, key) in enumerate((("Alb", "Albedo"), ("Nrm", "Normal"), ("Rha", "RHA"))):
        t = node(mat, unreal.MaterialExpressionTextureObjectParameter, -1100, 560 + 120 * k, parameter_name=pin, texture=arrays[key])
        t.set_editor_property("sampler_type", unreal.MaterialSamplerType.SAMPLERTYPE_COLOR if key == "Albedo" else
                              (unreal.MaterialSamplerType.SAMPLERTYPE_NORMAL if key == "Normal" else unreal.MaterialSamplerType.SAMPLERTYPE_LINEAR_COLOR))
        connect(t, "", c, pin)
    MEL.connect_material_property(c, "", unreal.MaterialProperty.MP_BASE_COLOR)
    MEL.connect_material_property(c, "Rough", unreal.MaterialProperty.MP_ROUGHNESS)
    MEL.connect_material_property(c, "WN", unreal.MaterialProperty.MP_NORMAL)
    MEL.connect_material_property(c, "AO", unreal.MaterialProperty.MP_AMBIENT_OCCLUSION)
    curve = custom(mat, CURVATURE_CODE, ["WP", "Cam"], -300, 500, [])
    connect(node(mat, unreal.MaterialExpressionWorldPosition, -600, 500), "", curve, "WP")
    connect(node(mat, unreal.MaterialExpressionCameraPositionWS, -600, 580), "", curve, "Cam")
    MEL.connect_material_property(curve, "", unreal.MaterialProperty.MP_WORLD_POSITION_OFFSET)
    MEL.recompile_material(mat)
    LIB.save_loaded_asset(mat)
    return mat


def main():
    if not os.path.exists(HLSL):
        raise FileNotFoundError(f"{HLSL} missing: python3 -I Tools/envloop/ground/ground_hlsl.py > {HLSL}")
    world_collection()
    arrays = {}
    kinds = (("Albedo", "A", True, unreal.TextureCompressionSettings.TC_DEFAULT),
             ("Normal", "N", False, unreal.TextureCompressionSettings.TC_NORMALMAP),
             ("RHA", "R", False, unreal.TextureCompressionSettings.TC_MASKS))
    if os.environ.get("GROUND_MATERIAL_ONLY") == "1":
        for key, _, _, _ in kinds:
            arrays[key] = unreal.load_asset(f"{GROUND}/TA_Ground_{key}")
            if arrays[key] is None:
                raise RuntimeError(f"TA_Ground_{key} missing: run without GROUND_MATERIAL_ONLY first")
    else:
        for key, suffix, srgb, compression in kinds:
            slices = [import_slice(role, suffix) for role in ROLES]
            arrays[key] = make_array(f"TA_Ground_{key}", slices, srgb, compression)
            unreal.log(f"Ground: TA_Ground_{key} from {len(slices)} slices at {RES}")
    build_material(arrays)
    unreal.log(f"Ground: M_Ground built from {HLSL} ({PACK})")


main()
